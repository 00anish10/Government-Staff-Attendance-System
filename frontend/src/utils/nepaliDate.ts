export interface BsDate {
  year: number;
  month: number;
  day: number;
  monthName: string;
  monthNameNp: string;
  dayName: string;
  dayNameNp: string;
}

export function adToBs(year: number, month: number, day: number): BsDate | null {
  try {
    const adStr = `${year}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
    const bsStr = libAdToBs(adStr);
    const parts = bsStr.split('-');
    if (parts.length !== 3) return null;
    const bs = { year: parseInt(parts[0]), month: parseInt(parts[1]), day: parseInt(parts[2]) };
    const monthData = bsMonths[bs.month - 1] || ['', ''];
    const date = new Date(year, month - 1, day);
    const dayData = bsDays[date.getDay()] || ['', ''];
    return {
      year: bs.year, month: bs.month, day: bs.day,
      monthName: monthData[0], monthNameNp: monthData[1],
      dayName: dayData[0], dayNameNp: dayData[1],
    };
  } catch {
    return null;
  }
}

export function toBsDateStr(adDateStr: string): string {
  const d = new Date(adDateStr);
  if (isNaN(d.getTime())) return '—';
  const bs = adToBs(d.getFullYear(), d.getMonth() + 1, d.getDate());
  if (!bs) return '—';
  return `${bs.day} ${bs.monthName} ${bs.year} B.S.`;
}

export function getTodayBs(): BsDate | null {
  const today = new Date();
  return adToBs(today.getFullYear(), today.getMonth() + 1, today.getDate());
}

export function bsToAd(bsYear: number, bsMonth: number, bsDay: number): Date | null {
  try {
    const bsStr = `${bsYear}-${String(bsMonth).padStart(2, '0')}-${String(bsDay).padStart(2, '0')}`;
    const adStr = libBsToAd(bsStr);
    return new Date(adStr);
  } catch {
    return null;
  }
}

export function bsToAdDateStr(bsYear: number, bsMonth: number, bsDay: number): string {
  const date = bsToAd(bsYear, bsMonth, bsDay);
  if (!date || isNaN(date.getTime())) return '';
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

export function getBsYearRange(): number[] {
  return Object.keys(nepaliYears).map(Number);
}

export function getDaysInBsMonth(bsYear: number, bsMonth: number): number {
  const months = nepaliYears[bsYear];
  if (!months || bsMonth < 1 || bsMonth > 12) return 30;
  return months[bsMonth - 1];
}

export const bsMonthList = bsMonths;

export function adDateStrToBs(adDateStr: string): { year: number; month: number; day: number } | null {
  const d = new Date(adDateStr);
  if (isNaN(d.getTime())) return null;
  const bs = adToBs(d.getFullYear(), d.getMonth() + 1, d.getDate());
  if (!bs) return null;
  return { year: bs.year, month: bs.month, day: bs.day };
}
